const assert = require('node:assert/strict');
const { randomUUID } = require('node:crypto');

module.exports = async function verify({ base, request, users, clients, password, event, first, models }) {
    const [organizer, other, student] = clients;
    const { Event, Registration } = models;
    const publicEvent = (await request({}, 'GET', '/events/' + event._id)).data;
    assert.equal(publicEvent.organizer.email, undefined);
    assert.equal(publicEvent.creationKey, undefined);
    assert.equal(publicEvent.creationFingerprint, undefined);
    const snapshot = JSON.stringify((await Registration.findById(first._id).lean()).attendee);
    const profile = (await request(student, 'GET', '/students/profile')).user;
    const saved = (await request(student, 'PATCH', '/students/profile', { version: profile.profileVersion, studentId: 'QA / 2026', department: 'Computer Science', studyStage: 'Year 3', contactNumber: '+92 300 1234567' })).user;
    assert.equal(saved.profileVersion, profile.profileVersion + 1);
    assert.equal(saved.studentProfile.studentId, 'QA / 2026');
    await request(student, 'PATCH', '/students/profile', { version: profile.profileVersion, name: 'A stale edit' }, 409);
    await request(student, 'PATCH', '/students/profile', { version: saved.profileVersion, role: 'organizer' }, 400);
    await request(organizer, 'GET', '/students/profile', undefined, 403);
    assert.equal(JSON.stringify((await Registration.findById(first._id).lean()).attendee), snapshot);
    const photo = await fetch(base + '/students/profile/photo', { method: 'POST', headers: { Cookie: student.cookie, 'X-CSRF-Token': student.csrf, 'X-Profile-Version': String(saved.profileVersion), 'Content-Type': 'image/svg+xml' }, body: '<svg></svg>' });
    assert.equal(photo.status, 415); await photo.arrayBuffer();
    const payload = { title: 'Final Handover Journey', description: 'A temporary integration fixture for final handover.', date: new Date(Date.now() + 86400000 * 10).toISOString(), category: 'Technology', location: 'Campus Lab', capacity: 1 };
    await request(student, 'POST', '/events', payload, 403);
    await request(organizer, 'POST', '/events', { ...payload, organizer: String(users[1]._id) }, 400);
    const key = randomUUID();
    const created = (await request(organizer, 'POST', '/events', payload, 201, organizer.csrf, { 'X-Idempotency-Key': key })).event;
    const replay = (await request(organizer, 'POST', '/events', payload, 200, organizer.csrf, { 'X-Idempotency-Key': key })).event;
    assert.equal(created._id, replay._id);
    await request(organizer, 'POST', '/events', { ...payload, title: 'Different creation' }, 409, organizer.csrf, { 'X-Idempotency-Key': key });
    await request(other, 'PATCH', '/events/' + created._id, { title: 'Not your event' }, 403, other.csrf, { 'X-Event-Version': '0' });
    await request(organizer, 'PATCH', '/events/' + created._id, { capacity: 2 }, 200, organizer.csrf, { 'X-Event-Version': '0' });
    await request(organizer, 'PATCH', '/events/' + created._id, { capacity: 3 }, 409, organizer.csrf, { 'X-Event-Version': '0' });
    await request(student, 'POST', '/events/' + created._id + '/register', {}, 400);
    await request(student, 'POST', '/events/' + created._id + '/register', { attendee: { ...first.attendee, email: 'invalid' } }, 400);
    await request(student, 'POST', '/events/' + created._id + '/register', { attendee: first.attendee }, 201);
    await request(organizer, 'DELETE', '/events/' + created._id, {}, 409, organizer.csrf, { 'X-Event-Version': '1' });
    await request(student, 'GET', '/events/' + created._id + '/registrations', undefined, 403);
    const dashboard = (await request(organizer, 'GET', '/organizer/dashboard')).data;
    const realTotal = await Registration.countDocuments({ event: { $in: await Event.find({ organizer: users[0]._id }).distinct('_id') }, status: { $in: ['active', null] } });
    assert.equal(dashboard.overview.activeRegistrations, realTotal);
    const histories = (await request(student, 'GET', '/registrations/me')).data;
    for (const record of histories) { assert.equal(record.student, undefined); assert.equal(record.cancellation?.actor, undefined); assert.equal(record.event?.organizer?.email, undefined); }
    const past = await Event.create({ ...payload, organizer: users[0]._id, date: new Date(0) });
    const recap = 'é'.repeat(9000);
    await request(organizer, 'PATCH', '/events/' + past._id + '/recap', { recap });
    assert.equal((await request({}, 'GET', '/events/' + past._id)).data.recap, recap);
    await request(other, 'PATCH', '/events/' + past._id + '/recap', { recap: 'Unauthorized' }, 403);
    await request(student, 'POST', '/events/' + past._id + '/register', { attendee: first.attendee }, 409);
    const empty = (await request(organizer, 'POST', '/events', { ...payload, title: 'Disposable Empty Event' }, 201)).event;
    await request(organizer, 'DELETE', '/events/' + empty._id, {}, 200, organizer.csrf, { 'X-Event-Version': '0' });
    await request({}, 'GET', '/events/' + empty._id, undefined, 404);
    for (const query of ['?limit=0', '?page=-1', '?search%5B%24ne%5D=x', '?category=invalid', '?scope=past&period=week']) await request({}, 'GET', '/events' + query, undefined, 400);
    const guest = {}; await request(guest, 'GET', '/auth/csrf-token');
    const email = 'handover-' + randomUUID() + '@eventnexus-seed.invalid';
    await request(guest, 'POST', '/auth/register', { name: 'Handover Student', email, password, role: 'organizer' }, 400);
    await request(guest, 'POST', '/auth/register', { name: 'Handover Student', email, password }, 201);
    await request(guest, 'POST', '/auth/register', { name: 'Handover Student', email, password }, 409);
    await request(guest, 'POST', '/auth/login', { email, password: 'wrong-password' }, 401);
    await request(guest, 'POST', '/auth/login', { email, password, role: 'organizer' }, 403);
    const cookieBefore = guest.cookie;
    await request(guest, 'POST', '/auth/login', { email, password, role: 'student' });
    assert.notEqual(guest.cookie, cookieBefore);
    await request(guest, 'POST', '/auth/logout', {});
    await request(guest, 'GET', '/auth/me', undefined, 401);
    await request(guest, 'PATCH', '/students/profile', { version: 0, name: 'Expired session' }, 403);
    console.log('PASS handover API journeys: signup/duplicate/role assertion/login rotation/logout/expired session; profile update/version/immutability/upload rejection; event creation replay/ownership/stale edits/deletion guards; MongoDB dashboard totals; public privacy; Unicode recap; invalid filters and registration inputs.');
};
