const router = require('express').Router();
const requireAuth = require('../middleware/requireAuth');
const requireRole = require('../middleware/requireRole');
const { getDashboard } = require('../controllers/organizerController');
const { getOwnedEvent, findCreation } = require('../controllers/eventManagementController');
router.use((req, res, next) => { res.set('Cache-Control', 'no-store'); next(); });
router.get('/dashboard', requireAuth, requireRole('organizer'), getDashboard);
router.get('/events/creation/:key', requireAuth, requireRole('organizer'), findCreation);
router.get('/events/:id', requireAuth, requireRole('organizer'), getOwnedEvent);
module.exports = router;
